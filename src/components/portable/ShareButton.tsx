export default function ShareButton({ title }: { title: string }) {
  const [open, setOpen] = useState(false);
  const [copied, setCopied] = useState(false);

  const url = typeof window !== "undefined" ? window.location.href : "";

  const copyLink = async () => {
    await navigator.clipboard.writeText(url);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="relative flex justify-center">
      {/* Pill button — "SHARE THIS ARTICLE" style */}
      <button
        onClick={() => setOpen((o) => !o)}
        aria-label="Share article"
        className="flex items-center gap-3 rounded-full border border-white/20 bg-transparent px-7 py-3 font-montserrat text-[11px] font-bold uppercase tracking-[0.3em] text-white transition-all hover:border-white/60 hover:bg-white/5"
      >
        <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
          <circle cx="18" cy="5" r="3" /><circle cx="6" cy="12" r="3" /><circle cx="18" cy="19" r="3" />
          <line x1="8.59" y1="13.51" x2="15.42" y2="17.49" /><line x1="15.41" y1="6.51" x2="8.59" y2="10.49" />
        </svg>
        Share This Article
      </button>

      {open && (
        <>
          <div className="fixed inset-0 z-40" onClick={() => setOpen(false)} />
          <div className="absolute left-1/2 top-14 z-50 w-52 -translate-x-1/2 overflow-hidden rounded-xl border border-white/10 bg-zinc-900 shadow-2xl">
            {platforms.map((p) => (
              <a
                key={p.label}
                href={p.getUrl(url, title)}
                target="_blank"
                rel="noopener noreferrer"
                onClick={() => setOpen(false)}
                className="flex items-center gap-3 px-4 py-3 font-montserrat text-xs text-white/70 transition-colors hover:bg-white/5 hover:text-white"
              >
                {p.icon}
                {p.label}
              </a>
            ))}
            <button
              onClick={copyLink}
              className="flex w-full items-center gap-3 border-t border-white/10 px-4 py-3 font-montserrat text-xs text-white/70 transition-colors hover:bg-white/5 hover:text-white"
            >
              {copied ? (
                <svg width="15" height="15" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2"><path d="M20 6L9 17l-5-5" /></svg>
              ) : (
                <svg width="15" height="15" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round"><rect x="9" y="9" width="13" height="13" rx="2" /><path d="M5 15H4a2 2 0 01-2-2V4a2 2 0 012-2h9a2 2 0 012 2v1" /></svg>
              )}
              {copied ? "Copied!" : "Copy link"}
            </button>
          </div>
        </>
      )}
    </div>
  );
}
